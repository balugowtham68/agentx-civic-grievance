const DICTIONARIES: Record<string, Dictionary> = { en, ta, te, hi }

/** Languages that have their own (partial) UI strings. */
export function hasUiStrings(language: string): boolean {
  return language !== 'en' && language in DICTIONARIES
}

export function translate(language: string, key: UIKey): string {
  return DICTIONARIES[language]?.[key] ?? en[key]
}

export type Translator = (key: UIKey) => string

export function translatorFor(language: string): Translator {
  return (key) => translate(language, key)
}
